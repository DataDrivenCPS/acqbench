#!/usr/bin/env python3
"""acquirium <ref>: DuckDB vs TimescaleDB timeseries backend, on the DPR CSVs.

For each run `<ref>:<backend>` (e.g. main:duckdb,main:timescale,ums-timescale-fix:timescale):
  1. (timescale) start a fresh timescale/timescaledb:latest-pg17 container
  2. start `acquirium server` (recreate=true, fresh data dir) from a clean venv
     built from a fresh shallow clone of <ref> of github.com/DataDrivenCPS/acquirium
  3. push DPRDriver at the 200 CSVs; time ingest from the per-file log lines,
     sampling server RSS/CPU and system memory every few seconds
  4. run the 30-query /timeseries workload (queries.py). results/queries.json is
     generated by the first run unless it already exists (copy the frozen set in
     to replay the identical queries across refs)
  5. record DB size / row count, stop everything, delete the data
     (data dir + duckdb file, or the postgres container + volume)

Usage: python3 bench_backends.py [--root DIR] [--data DIR] [--quick] [--runs main:duckdb,main:timescale]
"""
from __future__ import annotations

import argparse, json, os, re, shutil, signal, subprocess, sys, threading, time, urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO_URL = "https://github.com/DataDrivenCPS/acquirium.git"
PY_VERSION = "3.12"
BOOT_TIMEOUT_S, INGEST_TIMEOUT_S, IDLE_ABORT_S, POLL_S = 1800, 12 * 3600, 2400, 10
REPS, WARMUP = 10, 2
TSDB_IMAGE = "timescale/timescaledb:latest-pg17"
TSDB_NAME = "acq_bench_tsdb"
PG_DSN = "postgresql://acquirium:acquirium@127.0.0.1:5433/acquirium"
HERE = Path(__file__).resolve().parent
INSERTED_RE = re.compile(r": (\S.*?\.csv) \S+ inserted\s+([\d,]+)\s+(?:observation|row)", re.I)
LOGTS_RE = re.compile(r"(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)")


class Sampler(threading.Thread):
    """Every `every` s: RSS/CPU of the server session, postgres, system mem."""
    def __init__(self, path: Path, sid: int, pg: bool, every: float = 5.0):
        super().__init__(daemon=True)
        self.path, self.sid, self.pg, self.every, self.stop = path, sid, pg, every, threading.Event()
        self.peak = {"server_rss_mb": 0, "pg_rss_mb": 0}

    def sample(self) -> dict:
        out = subprocess.run(["ps", "-eo", "sid,comm,rss,cputimes"], capture_output=True, text=True).stdout
        srss = scpu = prss = pcpu = 0.0
        for line in out.splitlines()[1:]:
            p = line.split(None, 3)
            if len(p) < 4: continue
            if p[0] == str(self.sid):
                srss += float(p[2]) / 1024; scpu += float(p[3])
            elif self.pg and p[1].startswith("postgres"):
                prss += float(p[2]) / 1024; pcpu += float(p[3])
        mem = {}
        for l in open("/proc/meminfo"):
            k, v = l.split(":")
            if k in ("MemAvailable", "Cached"): mem[k] = int(v.split()[0]) // 1024
        cg = Path("/sys/fs/cgroup/memory.current")
        d = {"t": time.time(), "server_rss_mb": round(srss), "server_cpu_s": round(scpu, 1),
             "pg_rss_mb": round(prss), "pg_cpu_s": round(pcpu, 1),
             "mem_available_mb": mem.get("MemAvailable"), "cached_mb": mem.get("Cached"),
             "cgroup_mem_mb": int(cg.read_text()) // 2**20 if cg.exists() else None}
        self.peak["server_rss_mb"] = max(self.peak["server_rss_mb"], d["server_rss_mb"])
        self.peak["pg_rss_mb"] = max(self.peak["pg_rss_mb"], d["pg_rss_mb"])
        return d

    def run(self):
        with open(self.path, "a") as f:
            while not self.stop.is_set():
                try: f.write(json.dumps(self.sample()) + "\n"); f.flush()
                except Exception: pass
                self.stop.wait(self.every)


class Bench:
    def __init__(self, root: Path, data: Path, quick: bool):
        self.root, self.data, self.quick = root, data, quick
        self.results = root / "results"; self.results.mkdir(parents=True, exist_ok=True)
        self.logf = open(root / "bench.log", "a", buffering=1)
        self.n_files = len(list(data.glob("*.csv")))
        self.procs: list[subprocess.Popen] = []

    def log(self, m):
        line = f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {m}"; print(line, flush=True); self.logf.write(line + "\n")

    def run(self, cmd, cwd=None, timeout=1800, env=None, check=False):
        self.log("$ " + " ".join(map(str, cmd)))
        p = subprocess.run([str(c) for c in cmd], cwd=cwd, timeout=timeout, capture_output=True, text=True,
                           env={**os.environ, **(env or {})})
        if p.returncode != 0:
            self.log(f"  !! exit {p.returncode}\n  stdout: {p.stdout[-1500:]}\n  stderr: {p.stderr[-1500:]}")
            if check: raise RuntimeError(f"command failed: {cmd[0]}")
        return p

    # ------------------------------------------------------------ setup
    def prepare_code(self, ref: str) -> tuple[Path, Path, str]:
        """Fresh shallow clone of <ref> + fresh venv every time, so a ref is always its latest remote state."""
        safe = ref.replace("/", "_")
        repo, venv = self.root / f"repo_{safe}", self.root / f"venv_{safe}"
        shutil.rmtree(repo, ignore_errors=True); shutil.rmtree(venv, ignore_errors=True)
        self.run(["git", "clone", "--depth", "1", "--branch", ref, REPO_URL, repo], timeout=900, check=True)
        head = self.run(["git", "-C", repo, "rev-parse", "HEAD"]).stdout.strip()
        self.log(f"{ref} @ {head}")
        self.run(["uv", "venv", "--python", PY_VERSION, venv], timeout=900, check=True)
        self.run(["uv", "pip", "install", "--python", venv / "bin/python", "-e", "."], cwd=repo, timeout=2400, check=True)
        ver = self.run([venv / "bin/python", "-c", "import importlib.metadata as m; print(m.version('acquirium'))"]).stdout.strip()
        self.log(f"installed acquirium {ver}")
        return repo, venv / "bin/python", head

    def prepare_run(self, tag: str, backend: str, port: int) -> Path:
        rundir = self.root / tag / "run"
        shutil.rmtree(rundir, ignore_errors=True); rundir.mkdir(parents=True)
        store = ('timeseries_backend = "duckdb"\nduckdb_path = ".acquirium/timeseries.duckdb"\n'
                 if backend == "duckdb" else f'timeseries_backend = "timescale"\npg_dsn = "{PG_DSN}"\n')
        (rundir / "server.toml").write_text(
            f'[server]\nhost = "127.0.0.1"\nport = {port}\ndata_dir = ".acquirium"\n{store}recreate = true\n')
        (rundir / "driver.toml").write_text(f'''
[driver]
server_url  = "127.0.0.1"
server_port = {port}
use_ssl     = false

[[drivers]]
spec              = "{HERE / 'dpr_driver.py'}:DPRDriver"
interval          = 30.0
insert_batch_rows = 50000
source_id         = "dpr-trailer"
watch_dir         = "{self.data}"
glob              = "*.csv"
format            = "wide"
date_col          = "Date"
clock_col         = "Time"
date_format       = "%m/%d/%Y %I:%M:%S %p"
header_contains   = ["Date", "Time"]
null_values       = ["NaN"]
'''.lstrip())
        return rundir

    # ------------------------------------------------------------ timescale
    def tsdb_up(self) -> dict:
        self.run(["docker", "rm", "-f", "-v", TSDB_NAME])
        t0 = time.time()
        self.run(["docker", "run", "-d", "--name", TSDB_NAME, "-p", "127.0.0.1:5433:5432",
                  "-e", "POSTGRES_USER=acquirium", "-e", "POSTGRES_PASSWORD=acquirium",
                  "-e", "POSTGRES_DB=acquirium", "-e", "TS_TUNE_MEMORY=8GB", "-e", "TS_TUNE_NUM_CPUS=4",
                  "--shm-size=1g", TSDB_IMAGE], timeout=1200, check=True)
        while time.time() - t0 < 300:
            if self.run(["docker", "exec", TSDB_NAME, "pg_isready", "-U", "acquirium", "-d", "acquirium"]).returncode == 0:
                time.sleep(3)   # the entrypoint restarts postgres once after init
                if self.run(["docker", "exec", TSDB_NAME, "pg_isready", "-U", "acquirium", "-d", "acquirium"]).returncode == 0:
                    break
            time.sleep(2)
        else:
            raise TimeoutError("timescaledb not ready")
        ver = self.psql("SELECT version(); SELECT extversion FROM pg_extension WHERE extname='timescaledb'; "
                        "SHOW shared_buffers; SHOW work_mem; SHOW effective_cache_size; SHOW max_parallel_workers;")
        self.log(f"timescaledb ready in {time.time() - t0:.0f}s\n{ver}")
        return {"image": TSDB_IMAGE, "ready_s": round(time.time() - t0, 1), "settings": ver}

    def psql(self, sql: str) -> str:
        return self.run(["docker", "exec", TSDB_NAME, "psql", "-U", "acquirium", "-d", "acquirium", "-tA", "-c", sql],
                        timeout=3600).stdout.strip()

    def tsdb_stats(self) -> dict:
        d = {}
        try:
            d["db_bytes"] = int(self.psql("SELECT pg_database_size('acquirium')"))
            d["hypertable"] = self.psql("SELECT table_bytes, index_bytes, toast_bytes, total_bytes FROM hypertable_detailed_size('timeseries')")
            d["chunks"] = self.psql("SELECT count(*), count(*) FILTER (WHERE is_compressed) FROM timescaledb_information.chunks WHERE hypertable_name='timeseries'")
            d["compression"] = self.psql("SELECT before_compression_total_bytes, after_compression_total_bytes FROM hypertable_compression_stats('timeseries')")
            d["indexes"] = self.psql("SELECT indexname, hypertable_index_size(indexname::regclass) FROM pg_indexes WHERE tablename='timeseries' ORDER BY 1")
            d["row_count"] = int(self.psql("SELECT count(*) FROM timeseries"))
            d["streams"] = int(self.psql("SELECT count(*) FROM streams"))
            d["value_kinds"] = self.psql("SELECT value_kind, count(*) FROM streams GROUP BY 1")
        except Exception as e:
            d["error"] = str(e)
        return d

    def tsdb_down(self):
        self.run(["docker", "rm", "-f", "-v", TSDB_NAME])

    # ------------------------------------------------------------ server
    def start_server(self, rundir: Path, venv_py: Path, port: int) -> subprocess.Popen:
        logfile = open(rundir / "server.log", "w", buffering=1)
        p = subprocess.Popen([str(venv_py.parent / "acquirium"), "server", "--config", "server.toml"],
                             cwd=rundir, stdout=logfile, stderr=subprocess.STDOUT, start_new_session=True)
        self.procs.append(p)
        self.log(f"server pid={p.pid} port={port}, waiting for /health")
        t0 = time.time()
        while time.time() - t0 < BOOT_TIMEOUT_S:
            if p.poll() is not None: raise RuntimeError(f"server exited early ({p.returncode}); see server.log")
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{port}/health", timeout=5) as r:
                    if r.status == 200:
                        self.log(f"server healthy after {time.time() - t0:.0f}s"); return p
            except Exception: pass
            time.sleep(POLL_S)
        raise TimeoutError("server not healthy")

    def stop_all(self):
        for p in self.procs:
            if p.poll() is None:
                try: os.killpg(os.getpgid(p.pid), signal.SIGTERM)
                except Exception: p.terminate()
        t0 = time.time()
        for p in self.procs:
            while p.poll() is None and time.time() - t0 < 180: time.sleep(2)
            if p.poll() is None:
                try: os.killpg(os.getpgid(p.pid), signal.SIGKILL)
                except Exception: p.kill()
        self.procs.clear()
        subprocess.run("ray stop --force >/dev/null 2>&1; pkill -f 'ray::' ", shell=True)

    # ------------------------------------------------------------ ingest
    def ingest(self, rundir: Path, venv_py: Path, sampler: Sampler) -> dict:
        server_log = rundir / "server.log"
        s0 = sampler.sample()
        t0 = time.time()
        r = self.run([venv_py.parent / "acquirium", "driver", "start", "driver.toml"], cwd=rundir, timeout=1800)
        if r.returncode != 0: raise RuntimeError(f"driver start failed: {r.stderr[-800:]}")
        driver_start_s = time.time() - t0
        self.log(f"driver started (setup incl. graph insert + registration) in {driver_start_s:.1f}s")
        target, seen, rows, last_change, timeline = self.n_files, 0, 0, time.time(), []
        while True:
            time.sleep(POLL_S)
            text = server_log.read_text(errors="replace")
            # keyed by file: Ray can echo a worker log line twice
            hits = {f: int(h.replace(",", "")) for f, h in INSERTED_RE.findall(text)}
            n, total = len(hits), sum(hits.values())
            if n != seen:
                seen, rows, last_change = n, total, time.time()
                el = time.time() - t0
                timeline.append({"t_s": round(el, 1), "files": n, "rows": total})
                self.log(f"  ingest {n}/{target} files, {rows:,} rows, {rows/max(el,1):,.0f} rows/s, {el/60:.1f} min")
            if seen >= target: self.log("ingest complete"); break
            if time.time() - last_change > IDLE_ABORT_S: self.log(f"!! no progress for {IDLE_ABORT_S}s at {seen}/{target}"); break
            if time.time() - t0 > INGEST_TIMEOUT_S: self.log("!! ingest timeout"); break
        wall = time.time() - t0
        s1 = sampler.sample()
        # per-file wall from the driver's own log timestamps (first..last inserted line)
        ts = [LOGTS_RE.search(l).group(1) for l in text.splitlines() if INSERTED_RE.search(l) and LOGTS_RE.search(l)]
        log_span = None
        if len(ts) >= 2:
            f = lambda x: datetime.strptime(x, "%Y-%m-%d %H:%M:%S")
            log_span = (f(ts[-1]) - f(ts[0])).total_seconds()
        errors = len(re.findall(r"ERROR|Traceback", text))
        return {"files_ingested": seen, "files_total": target, "rows_inserted": rows, "complete": seen >= target,
                "driver_start_s": round(driver_start_s, 1),
                "wall_s": round(wall, 1), "rows_per_s": round(rows / max(wall, 1), 1),
                "log_span_first_to_last_file_s": log_span,
                "server_cpu_s": round(s1["server_cpu_s"] - s0["server_cpu_s"], 1),
                "pg_cpu_s": round(s1["pg_cpu_s"] - s0["pg_cpu_s"], 1),
                "cpu_utilisation_server": round((s1["server_cpu_s"] - s0["server_cpu_s"]) / max(wall, 1), 2),
                "cpu_utilisation_pg": round((s1["pg_cpu_s"] - s0["pg_cpu_s"]) / max(wall, 1), 2),
                "server_rss_mb_end": s1["server_rss_mb"], "pg_rss_mb_end": s1["pg_rss_mb"],
                "log_error_lines": errors, "timeline": timeline}

    # ------------------------------------------------------------ backend
    def run_one(self, ref: str, backend: str, port: int) -> dict:
        tag = f"{ref.replace('/', '_')}.{backend}"
        out = {"ref": ref, "backend": backend, "tag": tag, "port": port, "started": datetime.now(timezone.utc).isoformat()}
        pg = backend == "timescale"
        sampler = None
        venv_py = None
        try:
            repo, venv_py, head = self.prepare_code(ref)
            out["head"] = head
            rundir = self.prepare_run(tag, backend, port)
            if pg: out["tsdb"] = self.tsdb_up()
            b0 = time.time()
            srv = self.start_server(rundir, venv_py, port)
            out["boot_s"] = round(time.time() - b0, 1)
            sampler = Sampler(self.results / f"{tag}.samples.jsonl", srv.pid, pg); sampler.start()
            out["ingest"] = self.ingest(rundir, venv_py, sampler); self.save(tag, out)

            qfile = self.results / "queries.json"
            base = f"http://127.0.0.1:{port}"
            env = {"SERVER_SID": str(srv.pid)}
            if not qfile.exists():
                self.run([venv_py, HERE / "queries.py", "gen", base, HERE / "property_to_column.json", qfile], timeout=3600, check=True)
            self.log("query pass (30 queries x %d reps + %d warmup)" % ((REPS, WARMUP) if not self.quick else (3, 1)))
            qres = self.results / f"{tag}.queries.json"
            r = self.run([venv_py, HERE / "queries.py", "run", base, qfile, REPS if not self.quick else 3,
                          WARMUP if not self.quick else 1, qres] + (["pg"] if pg else []), timeout=4 * 3600, env=env)
            out["query_log"] = r.stderr[-6000:]
            out["query"] = json.load(open(qres)) if qres.exists() else {"error": r.stderr[-2000:]}
            out["peak_rss_mb"] = dict(sampler.peak)
            if pg: out["db"] = self.tsdb_stats()
        except Exception as e:
            out["error"] = f"{type(e).__name__}: {e}"; self.log(f"!! {tag} failed: {out['error']}")
        finally:
            if sampler: sampler.stop.set()
            self.stop_all(); time.sleep(5)
            rundir = self.root / tag / "run"
            if backend == "duckdb" and venv_py is not None:
                db = rundir / ".acquirium" / "timeseries.duckdb"
                if db.exists():
                    out["db"] = {"db_bytes": db.stat().st_size}
                    c = self.run([venv_py, "-c", f"import duckdb;c=duckdb.connect(r'{db}',read_only=True);"
                                  "print(c.execute('SELECT count(*) FROM timeseries').fetchone()[0]);"
                                  "print(c.execute('SELECT count(*) FROM streams').fetchone()[0]);"
                                  "print(c.execute('SELECT value_kind,count(*) FROM streams GROUP BY 1').fetchall())"], timeout=900)
                    if c.returncode == 0:
                        l = c.stdout.strip().splitlines()
                        out["db"].update({"row_count": int(l[0]), "streams": int(l[1]), "value_kinds": l[2]})
            if (rundir / "server.log").exists():
                shutil.copy(rundir / "server.log", self.results / f"{tag}.server.log")
            rows = out.get("ingest", {}).get("rows_inserted") or 0
            if rows and out.get("db", {}).get("db_bytes"):
                out["db"]["bytes_per_row"] = round(out["db"]["db_bytes"] / rows, 2)
            # delete everything
            shutil.rmtree(rundir, ignore_errors=True)
            if pg: self.tsdb_down()
            self.log(f"{tag}: data deleted")
        out["finished"] = datetime.now(timezone.utc).isoformat()
        self.save(tag, out)
        return out

    def save(self, tag, out):
        (self.results / f"{tag}.json").write_text(json.dumps(out, indent=1))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=Path.home() / "acq_bench2")
    ap.add_argument("--data", type=Path, default=Path.home() / "dpr_1")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--runs", default="main:duckdb,main:timescale", help="comma list of <git ref>:<duckdb|timescale>")
    a = ap.parse_args()
    b = Bench(a.root, a.data, a.quick)
    b.log("=" * 70); b.log(f"START runs={a.runs} data={a.data} ({b.n_files} csv) quick={a.quick}")
    try:
        for i, spec in enumerate(a.runs.split(",")):
            ref, be = spec.rsplit(":", 1)
            assert be in ("duckdb", "timescale"), spec
            b.log(f"----- run {ref}:{be} -----"); b.run_one(ref, be, 8100 + i)
    finally:
        b.stop_all()
    b.log("ALL DONE")


if __name__ == "__main__":
    main()
